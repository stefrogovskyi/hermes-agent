# 3. N-Gram Overlap Check (6-grams)
def normalize(txt):
    txt = txt.lower()
    txt = txt.translate(str.maketrans('', '', string.punctuation))
    return txt.split()

words_new = normalize(body)
words_orig = normalize(orig_body)

def get_ngrams(words, n=6):
    return set(tuple(words[i:i+n]) for i in range(len(words)-n+1))

ngrams_new = get_ngrams(words_new, 6)
ngrams_orig = get_ngrams(words_orig, 6)

overlap_6gram = ngrams_new.intersection(ngrams_orig)
print(f"3. 6-GRAM OVERLAPS COUNT: {len(overlap_6gram)}")
for g in overlap_6gram:
    print("   Overlap:", " ".join(g))

